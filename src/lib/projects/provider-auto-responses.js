import {
  OrgInspectionStatus,
  OrgOfferStatus,
  OrgOfferType,
  OrgProviderStatus,
  OrgSolicitationType,
  Prisma,
} from "@prisma/client";
import { writeAuditLog, AuditEvent } from "@/lib/audit-log";
import { PROVIDER_BEHAVIOUR, providerBehaviourLabel } from "@/lib/projects/provider-behaviours";
import { normalizeProviderCategories, normalizeProviderCategory } from "@/lib/projects/provider-terms";
import { findSolicitationForProcurement } from "@/lib/projects/solicitations";
import { getActiveOrderValue } from "@/lib/projects/contracts-lpo";
import { createInvoice, INVOICE_SOURCE } from "@/lib/projects/invoices";

export const OFFER_SOURCE = Object.freeze({ OFFICER: "OFFICER", PORTAL: "PORTAL", AUTO: "AUTO" });

/** Upper bound on simulated bidders responding to an advertised tender. */
const MAX_TENDER_AUTO_BIDDERS = 6;
const FALLBACK_ESTIMATE = 1_000_000;

/**
 * @param {number} min
 * @param {number} max
 */
function randBetween(min, max) {
  return min + Math.random() * (max - min);
}

/**
 * @param {number} value
 */
function roundToThousand(value) {
  return Math.max(1000, Math.round(value / 1000) * 1000);
}

/**
 * Price multiplier and response decision for a simulated provider behaviour.
 * @param {string | null} behaviour
 * @returns {{ responds: boolean; reason?: string; factor?: [number, number]; deliveryDays?: [number, number] }}
 */
function responsePlan(behaviour) {
  switch (behaviour) {
    case PROVIDER_BEHAVIOUR.NON_RESPONSIVE:
      return { responds: false, reason: "Did not respond to the invitation." };
    case PROVIDER_BEHAVIOUR.LATE_SUBMITTER:
      return { responds: false, reason: "Will miss the closing date (late submission is not accepted)." };
    case PROVIDER_BEHAVIOUR.COMPLIANT_COMPETITIVE:
      return { responds: true, factor: [0.86, 0.97], deliveryDays: [7, 21] };
    case PROVIDER_BEHAVIOUR.COMPLIANT_EXPENSIVE:
      return { responds: true, factor: [1.12, 1.3], deliveryDays: [7, 21] };
    case PROVIDER_BEHAVIOUR.POOR_DELIVERY:
      return { responds: true, factor: [0.8, 0.92], deliveryDays: [30, 60] };
    default:
      return { responds: true, factor: [0.94, 1.1], deliveryDays: [10, 30] };
  }
}

/**
 * Simulated providers (generated by the register) answer an issued RFQ or an
 * advertised tender according to their behaviour. Officer- or portal-entered
 * offers are never overwritten; providers that already responded are skipped.
 *
 * @param {import("@prisma/client").PrismaClient} prisma
 * @param {{ projectId: string; procurementId: string; solicitationType: string; actorOrgUserId?: string | null }} opts
 */
export async function autoRespondToSolicitation(prisma, opts) {
  const solicitation = await findSolicitationForProcurement(prisma, opts);
  if (!solicitation) return { ok: true, responded: [], skipped: [] };

  const procurement = await prisma.projectOrgProcurement.findFirst({
    where: { id: opts.procurementId, projectId: opts.projectId },
    select: {
      procurementNumber: true,
      requisition: { select: { estimatedTotalValue: true, category: true } },
    },
  });
  const estimate = Number(procurement?.requisition?.estimatedTotalValue || 0) || FALLBACK_ESTIMATE;
  const category = normalizeProviderCategory(procurement?.requisition?.category);
  const isRfq = opts.solicitationType === OrgSolicitationType.RFQ;

  const invitedIds = (solicitation.invites || []).map((i) => i.supplierId);
  /** @type {any[]} */
  let candidates = [];
  if (invitedIds.length) {
    candidates = await prisma.projectOrgProvider.findMany({
      where: { projectId: opts.projectId, id: { in: invitedIds }, isGenerated: true, status: OrgProviderStatus.ACTIVE },
    });
  }
  if (!isRfq) {
    const open = await prisma.projectOrgProvider.findMany({
      where: {
        projectId: opts.projectId,
        isGenerated: true,
        status: OrgProviderStatus.ACTIVE,
        id: { notIn: candidates.map((c) => c.id) },
      },
      orderBy: { createdAt: "asc" },
    });
    const matching = category
      ? open.filter((p) => normalizeProviderCategories(p.categories).includes(category))
      : open;
    candidates = [...candidates, ...matching].slice(0, MAX_TENDER_AUTO_BIDDERS);
  }
  if (!candidates.length) return { ok: true, responded: [], skipped: [] };

  const existing = await prisma.projectOrgOffer.findMany({
    where: { solicitationId: solicitation.id, status: { not: OrgOfferStatus.WITHDRAWN } },
    select: { supplierId: true },
  });
  const alreadyResponded = new Set(existing.map((o) => o.supplierId));

  const responded = [];
  const skipped = [];
  for (const provider of candidates) {
    if (alreadyResponded.has(provider.id)) continue;
    const plan = responsePlan(provider.behaviour);
    if (!plan.responds) {
      skipped.push({ supplierId: provider.id, name: provider.name, reason: plan.reason });
      continue;
    }
    const [lo, hi] = plan.factor || [0.95, 1.05];
    const [dLo, dHi] = plan.deliveryDays || [10, 30];
    const amount = roundToThousand(estimate * randBetween(lo, hi));
    const deliveryDays = Math.round(randBetween(dLo, dHi));
    const offer = await prisma.projectOrgOffer.create({
      data: {
        projectId: opts.projectId,
        procurementId: opts.procurementId,
        solicitationId: solicitation.id,
        supplierId: provider.id,
        offerType: isRfq ? OrgOfferType.QUOTATION : OrgOfferType.BID,
        amount: new Prisma.Decimal(amount.toFixed(2)),
        status: OrgOfferStatus.SUBMITTED,
        source: OFFER_SOURCE.AUTO,
        deliveryDays,
        remarks: `Simulated response (${providerBehaviourLabel(provider.behaviour)}).`,
      },
    });
    responded.push({ offerId: offer.id, supplierId: provider.id, name: provider.name, amount: amount.toFixed(2) });
  }

  if (responded.length || skipped.length) {
    await writeAuditLog({
      eventType: AuditEvent.PROJECT_ORG_OFFER_AUTO_RESPONDED,
      actorUserId: null,
      meta: {
        projectId: opts.projectId,
        procurementId: opts.procurementId,
        solicitationId: solicitation.id,
        solicitationType: opts.solicitationType,
        respondedCount: responded.length,
        skippedCount: skipped.length,
        responded,
        skipped,
        actorOrgUserId: opts.actorOrgUserId || null,
      },
    });
  }

  return { ok: true, responded, skipped };
}

/**
 * Value the provider is entitled to invoice after inspection: the order value
 * scaled by the share of ordered quantities accepted so far.
 *
 * @param {import("@prisma/client").PrismaClient} prisma
 * @param {{ projectId: string; procurementId: string; orderValue: number }} opts
 */
async function acceptedShareOfOrder(prisma, opts) {
  const deliveries = await prisma.projectOrgDelivery.findMany({
    where: {
      projectId: opts.projectId,
      procurementId: opts.procurementId,
      inspection: { status: { in: [OrgInspectionStatus.ACCEPTED, OrgInspectionStatus.PARTIAL] } },
    },
    include: { lines: true },
  });
  const items = await prisma.projectOrgRequisitionItem.findMany({
    where: { requisition: { procurements: { some: { id: opts.procurementId } } } },
    select: { itemName: true, quantity: true },
  });
  const ordered = items.reduce((sum, i) => sum + Number(i.quantity || 0), 0);
  if (!ordered) return opts.orderValue;
  let accepted = 0;
  for (const d of deliveries) {
    for (const l of d.lines || []) accepted += Number(l.acceptedQuantity || 0);
  }
  const share = Math.min(1, Math.max(0, accepted / ordered));
  return share > 0 ? opts.orderValue * share : opts.orderValue;
}

/**
 * After a delivery passes inspection, a simulated (generated) provider sends its
 * invoice automatically. INVOICE_MISMATCH providers deliberately send an amount
 * that does not match the order so the verifier has something to catch.
 *
 * @param {import("@prisma/client").PrismaClient} prisma
 * @param {{ projectId: string; procurementId: string }} opts
 */
export async function autoInvoiceFromGeneratedProvider(prisma, opts) {
  const order = await getActiveOrderValue(prisma, opts.projectId, opts.procurementId);
  if (!order?.supplierId) return { ok: true, skipped: "NO_ORDER" };

  const provider = await prisma.projectOrgProvider.findFirst({
    where: { id: order.supplierId, projectId: opts.projectId },
    select: { id: true, name: true, isGenerated: true, behaviour: true },
  });
  if (!provider?.isGenerated) return { ok: true, skipped: "NOT_SIMULATED" };

  const open = await prisma.projectOrgInvoice.count({
    where: {
      projectId: opts.projectId,
      procurementId: opts.procurementId,
      status: { in: ["RECEIVED", "CERTIFIED", "VERIFIED", "APPROVED_FOR_PAYMENT"] },
    },
  });
  if (open > 0) return { ok: true, skipped: "ALREADY_INVOICED" };

  const due = await acceptedShareOfOrder(prisma, {
    projectId: opts.projectId,
    procurementId: opts.procurementId,
    orderValue: order.value,
  });
  const mismatch = provider.behaviour === PROVIDER_BEHAVIOUR.INVOICE_MISMATCH;
  const amount = mismatch ? Math.round(due * randBetween(0.9, 0.97)) : Math.round(due * 100) / 100;

  const reference = `${provider.name
    .replace(/[^A-Za-z]/g, "")
    .slice(0, 4)
    .toUpperCase() || "PROV"}-INV-${Math.floor(randBetween(1000, 9999))}`;

  return createInvoice(prisma, {
    projectId: opts.projectId,
    procurementId: opts.procurementId,
    actorOrgUserId: null,
    actorRoleName: "Provider (simulated)",
    amount,
    source: INVOICE_SOURCE.AUTO,
    supplierReference: reference,
    notes: mismatch
      ? `Invoice issued against ${order.number}. Check the total against the order before verifying.`
      : `Invoice issued against ${order.number}.`,
  });
}
